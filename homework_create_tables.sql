-- Пересоздание таблиц
DROP TYPE IF EXISTS public.order_status CASCADE;
DROP TABLE IF EXISTS public.order_details;
DROP TABLE IF EXISTS public.orders;
DROP TABLE IF EXISTS public.products;
DROP TABLE IF EXISTS public.users;

CREATE TABLE public.users (
    user_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name         TEXT NOT NULL,
    email             TEXT NOT NULL UNIQUE,
    registration_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE public.products (
    product_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name      TEXT NOT NULL,
    description       TEXT,
    price             NUMERIC(10, 2) NOT NULL CHECK (price > 0),
    quantity_in_stock INTEGER NOT NULL CHECK (quantity_in_stock >= 0)
);

CREATE TYPE public.order_status AS ENUM (
    'В обработке',
    'Оплачен',
    'Отправлен',
    'Доставлен',
    'Отменён'
);

CREATE TABLE public.orders (
    order_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    order_date        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    status            public.order_status NOT NULL DEFAULT 'В обработке'
);

CREATE TABLE public.order_details (
    order_detail_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          INTEGER NOT NULL REFERENCES public.orders(order_id) ON DELETE CASCADE,
    product_id        INTEGER NOT NULL REFERENCES public.products(product_id),
    quantity          INTEGER NOT NULL CHECK(quantity > 0)
);